#!/usr/bin/env python3
"""Builds public/assets/js/globe-data.js for the home page globe.
Source: Natural Earth (public domain) 50m land, 110m coastline and 50m countries (for Nigeria).
Usage: python3 tools/make_globe.py <folder with the Natural Earth .geojson files>
Files: https://github.com/nvkelso/natural-earth-vector/tree/master/geojson"""
import json, math, base64, sys
from PIL import Image, ImageDraw

geo = sys.argv[1] if len(sys.argv) > 1 else 'raw/geo'
W, H = 4096, 2048
def px(lon, lat): return ((lon + 180) / 360 * W, (90 - lat) / 180 * H)

def mask(geometry_list):
    m = Image.new('L', (W, H), 0); d = ImageDraw.Draw(m)
    for g in geometry_list:
        polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
        for poly in polys:
            d.polygon([px(*p) for p in poly[0]], fill=255)
            for hole in poly[1:]: d.polygon([px(*p) for p in hole], fill=0)
    return m

land = mask([f['geometry'] for f in json.load(open(f'{geo}/ne_50m_land.geojson'))['features']])
countries = json.load(open(f'{geo}/ne_50m_admin_0_countries.geojson'))['features']
nigeria = mask([f['geometry'] for f in countries if f['properties'].get('ADM0_A3') == 'NGA'])

# Evenly spaced points on the sphere (Fibonacci lattice); the browser rebuilds the same lattice from N.
N = 16000
ga = math.pi * (3 - math.sqrt(5))
bits = bytearray((N + 7) // 8); ng = []
for i in range(N):
    y = 1 - (i + .5) / N * 2; r = math.sqrt(1 - y * y); th = ga * i
    lat = math.degrees(math.asin(y)); lon = math.degrees(math.atan2(math.sin(th) * r, math.cos(th) * r))
    x, yy = px(lon, lat); p = (min(W - 1, int(x)), min(H - 1, int(yy)))
    if land.getpixel(p): bits[i >> 3] |= 1 << (i & 7)
    if nigeria.getpixel(p): ng.append(i)

lines = []
for f in json.load(open(f'{geo}/ne_110m_coastline.geojson'))['features']:
    g = f['geometry']; ls = g['coordinates'] if g['type'] == 'MultiLineString' else [g['coordinates']]
    for l in ls:
        pts = []
        for lon, lat in l:
            q = [round(lon * 4), round(lat * 4)]  # quarter-degree precision
            if not pts or q != pts[-1]: pts.append(q)
        if len(pts) > 1: lines.append([c for p in pts for c in p])

data = {'n': N, 'land': base64.b64encode(bytes(bits)).decode(), 'nigeria': ng, 'coast': lines}
out = 'public/assets/js/globe-data.js'
open(out, 'w').write('/* Generated by tools/make_globe.py from Natural Earth (public domain). */\nwindow.NIDA_GLOBE=' + json.dumps(data, separators=(',', ':')) + ';\n')
print(f'{out}: {len(ng)} Nigeria points, {len(lines)} coastlines')
